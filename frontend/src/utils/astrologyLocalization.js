/**
 * Resolves localized Tamil / Vedic Date (e.g. "Aavani 16, Parabhava" -> "ஆவணி 16, பராபவ")
 * Translates ONLY the Tamil Year into all 6 languages (ta, hi, te, kn, ml, en).
 * The Tamil Month is kept as the Tamil calendar month (in Tamil script for 'ta' or English for 'en').
 */
export function getLocalizedTamilDate(tamilDateStr, lang = 'ta') {
  if (!tamilDateStr || typeof tamilDateStr !== 'string') return tamilDateStr;
  const targetLang = getNormLang(lang);

  let result = tamilDateStr;

  // 1. Search for matching Tamil Year (longest match first)
  let matchedYear = null;
  let matchedYearToken = null;
  for (const entry of YEAR_SEARCH_TOKENS) {
    const isAscii = /^[a-zA-Z0-9\s()/-]+$/.test(entry.token);
    let found = false;
    let foundStr = '';

    if (isAscii) {
      const reg = new RegExp(`(^|[^a-zA-Z0-9])${escapeRegexStr(entry.token)}([^a-zA-Z0-9]|$)`, 'i');
      if (reg.test(result)) {
        found = true;
        foundStr = entry.token;
      }
    } else {
      if (result.includes(entry.token)) {
        found = true;
        foundStr = entry.token;
      }
    }

    if (found) {
      matchedYear = entry.item;
      matchedYearToken = foundStr;
      break;
    }
  }

  // 2. Normalize Month: only between Tamil ('ta') and English ('en')
  if (targetLang === 'ta') {
    for (const m of TAMIL_MONTHS_6LANG) {
      const reg = new RegExp(`(^|[^a-zA-Z0-9])${escapeRegexStr(m.en)}([^a-zA-Z0-9]|$)`, 'i');
      if (reg.test(result)) {
        result = result.replace(reg, `$1${m.ta}$2`);
        break;
      }
    }
  } else if (targetLang === 'en') {
    for (const m of TAMIL_MONTHS_6LANG) {
      if (result.includes(m.ta)) {
        result = result.replace(m.ta, m.en);
        break;
      }
    }
  }

  // 3. Translate ONLY the Tamil Year into the target language (all 6 languages supported)
  if (matchedYear && matchedYearToken) {
    const targetYearName = matchedYear[targetLang] || matchedYear.en;
    const isAscii = /^[a-zA-Z0-9\s()/-]+$/.test(matchedYearToken);
    if (isAscii) {
      const reg = new RegExp(`(^|[^a-zA-Z0-9])${escapeRegexStr(matchedYearToken)}([^a-zA-Z0-9]|$)`, 'i');
      result = result.replace(reg, `$1${targetYearName}$2`);
    } else {
      result = result.replace(matchedYearToken, targetYearName);
    }
  }

  return result;
}

