/**
 * Localizes enriched planet list
 */
export function localizePlanets(planets = [], lang = 'ta') {
  if (!planets || !Array.isArray(planets)) return [];
  const targetLang = getNormLang(lang);

  return planets.map((p) => {
    const locPlanet = getLocalizedPlanet(p.name, targetLang);
    const locRasi = getLocalizedRasi(p.rasiId, targetLang);
    const locNak = getLocalizedNakshatra(p.nakshatraId, targetLang);
    const locNavamsa = getLocalizedRasi(p.navamsaRasiId, targetLang);

    const rasiAthipathi = (p.rasiAthipathi && p.rasiAthipathi.name)
      ? {
          ...p.rasiAthipathi,
          name: getLocalizedPlanet(p.rasiAthipathi.name, targetLang).name
        }
      : null;

    const nakAthipathi = (p.nakshatraAthipathi && p.nakshatraAthipathi.name)
      ? {
          ...p.nakshatraAthipathi,
          name: getLocalizedPlanet(p.nakshatraAthipathi.name, targetLang).name
        }
      : null;

    const padamAthipathi = (p.padamAthipathi && p.padamAthipathi.name)
      ? {
          ...p.padamAthipathi,
          name: getLocalizedPlanet(p.padamAthipathi.name, targetLang).name
        }
      : null;

    return {
      ...p,
      displayName: locPlanet.name,
      nameTa: targetLang === 'ta' ? locPlanet.name : p.nameTa,
      shortName: locPlanet.short,
      shortNameTa: targetLang === 'ta' ? locPlanet.short : p.shortNameTa,
      rasiName: locRasi,
      rasiNameTa: targetLang === 'ta' ? locRasi : p.rasiNameTa,
      rasiAthipathi,
      nakshatraName: locNak,
      nakshatraNameTa: targetLang === 'ta' ? locNak : p.nakshatraNameTa,
      nakshatraAthipathi: nakAthipathi,
      navamsaRasiName: locNavamsa,
      navamsaRasiNameTa: targetLang === 'ta' ? locNavamsa : p.navamsaRasiNameTa,
      padamAthipathi,
      ...(p.maandiDetails ? { maandiDetails: p.maandiDetails } : {})
    };
  });
}

/**
 * Reconstructs 12-house Rasi and Navamsa grids from localized planet list
 */
export function reconstructLocalizedGrids(localizedPlanets) {
  const rasiGrid = Array.from({ length: 12 }, () => []);
  const navamsaGrid = Array.from({ length: 12 }, () => []);

  localizedPlanets.forEach((p) => {
    if (p.rasiId >= 0 && p.rasiId < 12) {
      rasiGrid[p.rasiId].push(p);
    }
    if (p.navamsaRasiId >= 0 && p.navamsaRasiId < 12) {
      navamsaGrid[p.navamsaRasiId].push(p);
    }
  });

  rasiGrid.forEach((house) => house.sort((a, b) => (a.degreeInRasi || 0) - (b.degreeInRasi || 0)));
  navamsaGrid.forEach((house) => house.sort((a, b) => (a.degreeInRasi || 0) - (b.degreeInRasi || 0)));

  return { rasiGrid, navamsaGrid };
}

/**
 * Full Saved Horoscope Profile Localizer
 * Converts a database record (stored in English) into a rich, reactive, 6-language representation
 * based on the active language selected on the frontend.
 */
export function localizeSavedProfile(profile, lang = 'ta') {
  if (!profile) return null;
  const targetLang = getNormLang(lang);

  const person = profile.personDetails || {};
  const location = profile.location || {};
  const astro = profile.astronomicalDetails || {};
  const birthAstro = profile.birthAstrology || {};
  const rawBasic = profile.basicDetails || {};

  // Localize Birth Astrology specifications
  const janmaNakId = birthAstro.janmaNakshatra?.nakshatraId ?? 0;
  const janmaRasiId = birthAstro.janmaRasi?.rasiId ?? 0;
  const lagnaRasiId = birthAstro.lagna?.rasiId ?? astro.ascendantRasiId ?? 6;

  const localizedStarName = getLocalizedNakshatra(janmaNakId, targetLang);
  const localizedPadaStr = getLocalizedPada(birthAstro.janmaNakshatra?.pada || 1, targetLang);
  const localizedRasiName = getLocalizedRasi(janmaRasiId, targetLang);
  const localizedLagnaName = getLocalizedRasi(lagnaRasiId, targetLang);
  const localizedGender = getLocalizedGender(person.gender, targetLang);
  const localizedAyanamsa = getLocalizedAyanamsa(astro.ayanamsaMode || astro.ayanamsaType, targetLang);

  // Localize Maandi planet specifications
  const rawMaandi = birthAstro.maandi || (profile.planets || []).find(p => p.name === 'Maandi' || p.name === 'Mandi') || null;
  const maandiRasiId = rawMaandi?.rasiId;
  const localizedMaandiRasiName = maandiRasiId !== undefined ? getLocalizedRasi(maandiRasiId, targetLang) : '';
  const localizedMaandiStarName = rawMaandi?.nakshatraId !== undefined ? getLocalizedNakshatra(rawMaandi.nakshatraId, targetLang) : '';
  const localizedMaandiPada = rawMaandi?.pada ? getLocalizedPada(rawMaandi.pada, targetLang) : '';
  const maandiDegree = rawMaandi?.formattedDegree || (rawMaandi?.degreeInRasi !== undefined ? `${Math.floor(rawMaandi.degreeInRasi)}°${Math.floor((rawMaandi.degreeInRasi % 1) * 60).toString().padStart(2, '0')}'` : '');

  // Localize Planet List and Grids
  const localizedPlanets = localizePlanets(profile.planets || [], targetLang);
  const { rasiGrid, navamsaGrid } = reconstructLocalizedGrids(localizedPlanets);

  // Localize Basic Details
  const localizedBasicDetails = localizeBasicDetails(rawBasic, janmaNakId, targetLang);

  const maandiPlanet = localizedPlanets.find(p => p.name === 'Maandi' || p.name === 'Mandi') || null;

  const chartResult = {
    rasiGrid,
    navamsaGrid,
    planets: localizedPlanets,
    ascendantRasiId: astro.ascendantRasiId,
    ascendantNavamsaRasiId: astro.ascendantNavamsaRasiId,
    lagnaDetails: localizedPlanets.find(p => p.name === 'Lagna') || null,
    maandiDetails: rawMaandi?.maandiDetails || profile.maandiDetails || maandiPlanet?.maandiDetails || null,
    maandiPlanet,
    formattedAddress: location.formattedAddress || location.placeName,
    latitude: location.latitude,
    longitude: location.longitude,
    gmt: person.gmt || location.gmt || '+05:30',
    dst: person.dst || location.dst || '+00:00',
    timezone: person.timeZone || location.timezone || 'Asia/Kolkata',
    ayanamsa: typeof astro.ayanamsa === 'number' ? astro.ayanamsa.toFixed(4) : astro.ayanamsa,
    ayanamsaType: localizedAyanamsa,
    ayanamsaName: localizedAyanamsa,
    ayanamsaNameTa: targetLang === 'ta' ? localizedAyanamsa : '',
    moonNakshatra: localizedStarName,
    basicDetails: localizedBasicDetails,
    dob: person.dob,
    tob: person.tob
  };

  return {
    ...profile,
    personDetails: {
      ...person,
      genderDisplay: localizedGender
    },
    birthAstrologyDisplay: {
      rasiName: localizedRasiName,
      starName: localizedStarName,
      padaStr: localizedPadaStr,
      lagnaName: localizedLagnaName,
      maandiRasiName: localizedMaandiRasiName,
      maandiStarName: localizedMaandiStarName,
      maandiPadaStr: localizedMaandiPada,
      maandiDegree
    },
    astronomicalDetails: {
      ...astro,
      ayanamsaName: localizedAyanamsa,
      ayanamsaType: localizedAyanamsa,
      ayanamsaDisplay: localizedAyanamsa
    },
    astronomicalDetailsDisplay: {
      ayanamsaName: localizedAyanamsa,
      ayanamsaDisplay: localizedAyanamsa
    },
    chartResult
  };
}

/**
 * Localizes a single 360° Kalachakram degree item into the selected 6-language representation
 */
export function localizeKalachakramItem(item, lang = 'ta') {
  if (!item) return null;
  const targetLang = getNormLang(lang);
  const langSuffixMap = { ta: 'Ta', hi: 'Hi', te: 'Te', kn: 'Kn', ml: 'Ml', en: '' };
  const suffix = langSuffixMap[targetLang] || '';

  const rasiId = item.rasiId ?? Math.floor(item.degree / 30);
  const nakshatraId = item.nakshatraId ?? Math.floor(item.degree / (360 / 27));
  const totalPadaIndex = item.totalPadaIndex ?? Math.floor(item.degree / (360 / 108));
  const pada = item.pada ?? ((totalPadaIndex % 4) + 1);
  const navamsaRasiId = item.navamsaRasiId ?? (totalPadaIndex % 12);
  const degreeInRasi = item.degreeInRasi ?? (item.degree % 30);

  const rasiName = (suffix && item[`rasiName${suffix}`]) || item.rasiName || getLocalizedRasi(rasiId, targetLang);
  const nakshatraName = (suffix && item[`nakshatraName${suffix}`]) || item.nakshatraName || getLocalizedNakshatra(nakshatraId, targetLang);
  const navamsaRasiName = (suffix && item[`navamsaRasiName${suffix}`]) || item.navamsaRasiName || getLocalizedRasi(navamsaRasiId, targetLang);

  const rasiLord = getLocalizedPlanet(item.rasiAthipathi?.planetId, targetLang);
  const starLord = getLocalizedPlanet(item.nakshatraAthipathi?.planetId, targetLang);
  const navamsaLord = getLocalizedPlanet(item.navamsaAthipathi?.planetId, targetLang);

  return {
    ...item,
    degree: item.degree,
    degreeInRasi,
    rasiId,
    nakshatraId,
    pada,
    navamsaRasiId,
    degreeDisplay: item.degreeDisplay || `${item.degree}° - ${item.degree + 1}°`,
    degreeInRasiDisplay: `${degreeInRasi}°`,
    rasiName,
    rasiLord,
    nakshatraName,
    starLord,
    padaStr: formatPadaLabel(pada, targetLang),
    navamsaRasiName,
    navamsaLord
  };
}

/**
 * Localizes a full list of Kalachakram degree items
 */
export function localizeKalachakramList(list = [], lang = 'ta') {
  if (!Array.isArray(list)) return [];
  return list.map(item => localizeKalachakramItem(item, lang));
}

