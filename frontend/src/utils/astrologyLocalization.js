// Helper to normalize language code
export const getNormLang = (lang) => {
  const l = (lang || 'ta').toLowerCase();
  return ['ta', 'hi', 'te', 'kn', 'ml', 'en'].includes(l) ? l : 'ta';
};

// Precompiled search tokens sorted by length descending for collision-free matching
const buildSearchIndex = (items) => {
  const list = [];
  items.forEach((item) => {
    const rawCandidates = [
      item.en,
      item.ta,
      item.hi,
      item.te,
      item.kn,
      item.ml,
      ...(item.aliases || [])
    ];
    rawCandidates.forEach((cand) => {
      if (cand && typeof cand === 'string' && cand.trim().length > 0) {
        list.push({
          token: cand.trim(),
          tokenLower: cand.trim().toLowerCase(),
          item
        });
      }
    });
  });
  list.sort((a, b) => b.token.length - a.token.length);
  return list;
};

const MONTH_SEARCH_TOKENS = buildSearchIndex(TAMIL_MONTHS_6LANG);
const YEAR_SEARCH_TOKENS = buildSearchIndex(TAMIL_YEARS_6LANG);

const escapeRegexStr = (str) => str.replace(/[-\/\\^$*+?.()|[\]{}]/g, '\\$&');

